// Phase 3J-AU/AV: the LumiTale sync copy and its publication gate.
// Run: npm test (node --test, no dependencies). Tests that need LumiTale's
// legal package read it from a local LumiTale checkout (it is never committed
// here while it is a draft) and are skipped where none exists.
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { test } from "node:test";

import {
  MANIFEST,
  PRODUCT_PUBLIC,
  ROOT,
  decide,
  listFiles,
  lumitaleCheckout,
  normalized,
  publicationProblems,
  verifyIntegrity,
} from "../scripts/lib/lumitale-package.mjs";

const checkout = lumitaleCheckout();
const needsCheckout = !checkout && "no local LumiTale checkout (set LUMITALE_V2_DIR)";

const jwt = (payload) =>
  ["e30", Buffer.from(JSON.stringify(payload)).toString("base64url"), "sig"].join(".");

/** A temporary legal package copied (normalised) from the LumiTale checkout. */
function legalFixture() {
  const dir = mkdtempSync(path.join(tmpdir(), "lumitale-legal-"));
  const source = path.join(checkout, "website", "lumitale");
  for (const rel of listFiles(source)) {
    const target = path.join(dir, rel);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, normalized(path.join(source, rel)));
  }
  return { dir, cleanup: () => rmSync(dir, { recursive: true, force: true }) };
}

/** What counsel and the owner will have done: markers resolved, real key. */
function resolve(legalDir, key = jwt({ role: "anon", iss: "supabase" })) {
  for (const route of ["privacy", "terms", "delete-account"]) {
    const file = path.join(legalDir, route, "index.html");
    const html = readFileSync(file, "utf8").replace(
      /<(div|span) class="(legal-review|legal-decision|draft-banner)"[\s\S]*?<\/\1>/g,
      "<p>Counsel-approved text.</p>",
    );
    writeFileSync(file, html);
  }
  const config = path.join(legalDir, "assets", "config.js");
  writeFileSync(config, readFileSync(config, "utf8").replace(/publishableKey: "[^"]*"/, `publishableKey: "${key}"`));
}

test("the committed sync copy is intact", () => {
  assert.deepEqual(verifyIntegrity(), []);
});

test("no LumiTale draft is tracked in this public repository", () => {
  const tracked = spawnSync("git", ["ls-files", "vendor", "public"], { cwd: ROOT, encoding: "utf8" }).stdout;
  assert.ok(!/vendor\/lumitale\/legal\//.test(tracked), "draft legal package must not be committed");
  assert.ok(!/public\/lumitale\//.test(tracked), "public/lumitale is generated by the gate only");
  const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
  assert.equal(manifest.legalIncluded, false);
  assert.deepEqual(manifest.legal, {});
});

test("an edited, removed or extra generated file is detected", () => {
  const dir = mkdtempSync(path.join(tmpdir(), "lumitale-gate-"));
  try {
    const product = path.join(dir, "product");
    const legal = path.join(dir, "legal");
    const manifest = path.join(dir, "manifest.json");
    cpSync(PRODUCT_PUBLIC, product, { recursive: true });
    cpSync(MANIFEST, manifest);
    const args = { manifestPath: manifest, legalDir: legal, productDir: product };
    assert.deepEqual(verifyIntegrity(args), []);
    writeFileSync(path.join(product, "lumitale-wordmark.png"), "edited by hand");
    rmSync(path.join(product, "lumitale-hero.png"));
    mkdirSync(legal, { recursive: true });
    writeFileSync(path.join(legal, "privacy.html"), "a draft copied by hand");
    assert.deepEqual(verifyIntegrity(args).sort(), [
      "legal/privacy.html: not from the sync",
      "product/lumitale-hero.png: missing",
      "product/lumitale-wordmark.png: changed since sync",
    ]);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("without a synced (ready) legal package nothing can be published", () => {
  assert.deepEqual(publicationProblems(), [
    "legal package not synced (it is synced only once counsel-approved and ready)",
  ]);
  const manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
  assert.equal(manifest.publishCheck.ready, false, "LumiTale's own validator recorded NOT READY");
});

test("today's LumiTale drafts are not publishable (markers + placeholder key)", { skip: needsCheckout }, () => {
  const f = legalFixture();
  try {
    const problems = publicationProblems(f.dir);
    assert.ok(problems.some((p) => p.includes("unresolved legal-review markers")));
    assert.ok(problems.includes("config: publishable key not set"));
  } finally {
    f.cleanup();
  }
});

test("a resolved package with a publishable key is publishable", { skip: needsCheckout }, () => {
  const f = legalFixture();
  try {
    resolve(f.dir);
    assert.deepEqual(publicationProblems(f.dir), []);
  } finally {
    f.cleanup();
  }
});

test("privileged, local, placeholder keys and a wrong canonical URL are refused", { skip: needsCheckout }, () => {
  const cases = [
    [jwt({ role: "service_role" }), "config: a privileged key must never be published"],
    ["sb_secret_abcdefghijklmnopqrstuvwxyz", "config: a privileged key must never be published"],
    [jwt({ role: "anon", iss: "supabase-demo" }), "config: the local development key"],
    ["<PUBLISHABLE KEY>", "config: publishable key not set"],
    ["not-a-key-but-long-enough-xx", "config: not a publishable (anon) key"],
  ];
  for (const [key, expected] of cases) {
    const f = legalFixture();
    try {
      resolve(f.dir, key);
      assert.deepEqual(publicationProblems(f.dir), [expected], key.slice(0, 12));
    } finally {
      f.cleanup();
    }
  }
  const f = legalFixture();
  try {
    resolve(f.dir);
    const file = path.join(f.dir, "terms", "index.html");
    writeFileSync(file, readFileSync(file, "utf8").replace("https://nkdigitalworks.com/lumitale/terms", "https://www.nkdigitalworks.com/lumitale/terms"));
    assert.deepEqual(publicationProblems(f.dir), [
      "terms: canonical URL is not https://nkdigitalworks.com/lumitale/terms",
    ]);
  } finally {
    f.cleanup();
  }
});

test("publication decision: approval, local drafts, Vercel, default", () => {
  const notReady = { ready: false, problems: ["markers"] };
  const ready = { ready: true, problems: [] };
  // Default production build: withheld, the build continues.
  assert.equal(decide({ mode: "build", env: { VERCEL: "1" }, ...notReady }).action, "withhold");
  assert.equal(decide({ mode: "build", env: {}, ...ready }).action, "withhold");
  // Approval publishes only a ready package and fails loudly otherwise.
  assert.equal(decide({ mode: "build", env: { VERCEL: "1", LUMITALE_LEGAL_PUBLISH: "approved" }, ...ready }).action, "publish");
  assert.equal(decide({ mode: "build", env: { VERCEL: "1", LUMITALE_LEGAL_PUBLISH: "approved" }, ...notReady }).action, "fail");
  assert.equal(decide({ mode: "build", env: { LUMITALE_LEGAL_PUBLISH: "yes" }, ...ready }).action, "withhold");
  // Drafts only locally, never on Vercel (preview or production).
  assert.equal(decide({ mode: "dev", env: {}, ...notReady }).action, "draft");
  assert.equal(decide({ mode: "build", env: { LUMITALE_LEGAL_DRAFTS: "local" }, ...notReady }).action, "draft");
  assert.equal(decide({ mode: "dev", env: { VERCEL: "1" }, ...notReady }).action, "withhold");
  assert.equal(decide({ mode: "build", env: { VERCEL: "1", LUMITALE_LEGAL_DRAFTS: "local" }, ...notReady }).action, "withhold");
});

test("the real gate in a Vercel-like build: withheld by default, fails if approved", () => {
  const run = (env) =>
    spawnSync(process.execPath, [path.join(ROOT, "scripts", "lumitale-legal-gate.mjs")], {
      cwd: ROOT,
      env: { ...process.env, VERCEL: "1", LUMITALE_LEGAL_DRAFTS: "", LUMITALE_LEGAL_PUBLISH: "", ...env },
      encoding: "utf8",
    });
  const withheld = run({});
  assert.equal(withheld.status, 0);
  assert.match(withheld.stdout, /withheld, routes return 404/);
  assert.equal(run({ LUMITALE_LEGAL_PUBLISH: "approved" }).status, 1);
  assert.equal(run({ LUMITALE_LEGAL_DRAFTS: "local" }).status, 0);
  assert.equal(listFiles(path.join(ROOT, "public", "lumitale")).length, 0, "nothing placed in public/");
});
